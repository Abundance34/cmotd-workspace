-- 011: Expense reconciliation and controlled return of unspent employee advances.
CREATE TABLE IF NOT EXISTS expense_reconciliations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reference TEXT NOT NULL UNIQUE,
 request_id BIGINT NOT NULL REFERENCES purchase_requests(id) ON DELETE RESTRICT,
 submitted_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 funding_type TEXT NOT NULL CHECK (funding_type IN ('Employee Advance','Budget Only')),
 amount_released NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(amount_released>=0),
 budget_snapshot NUMERIC(18,2) NOT NULL CHECK(budget_snapshot>=0),
 actual_spent NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(actual_spent>=0),
 unspent_amount NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(unspent_amount>=0),
 status TEXT NOT NULL DEFAULT 'Draft' CHECK(status IN ('Draft','Submitted','Returned for Correction','Rejected','Approved','Refund Submitted','Partially Refunded','Completed')),
 explanation TEXT,
 reviewer_id BIGINT REFERENCES users(id),
 review_note TEXT, reviewed_at TIMESTAMPTZ,
 submitted_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT exp_reconcile_budget CHECK (actual_spent=0 OR actual_spent <= budget_snapshot OR length(coalesce(explanation,'')) >= 10)
);
CREATE TABLE IF NOT EXISTS expense_reconciliation_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reconciliation_id BIGINT NOT NULL REFERENCES expense_reconciliations(id) ON DELETE CASCADE,
 request_item_id BIGINT NOT NULL REFERENCES purchase_request_items(id) ON DELETE RESTRICT,
 item_name_snapshot TEXT NOT NULL,
 approved_qty NUMERIC(18,4) NOT NULL, approved_unit_price NUMERIC(18,4) NOT NULL,
 actual_qty NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK(actual_qty>=0),
 actual_unit_price NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(actual_unit_price>=0),
 line_total NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(line_total>=0),
 note TEXT, UNIQUE(reconciliation_id,request_item_id)
);
CREATE TABLE IF NOT EXISTS expense_reconciliation_refunds (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reconciliation_id BIGINT NOT NULL REFERENCES expense_reconciliations(id) ON DELETE RESTRICT,
 submitted_by BIGINT NOT NULL REFERENCES users(id),
 amount NUMERIC(18,2) NOT NULL CHECK(amount>0),
 transfer_reference TEXT NOT NULL,
 transfer_date DATE NOT NULL,
 evidence_name TEXT, evidence_mime TEXT, evidence_base64 TEXT,
 status TEXT NOT NULL DEFAULT 'Pending Verification' CHECK(status IN ('Pending Verification','Verified','Rejected')),
 verified_by BIGINT REFERENCES users(id),
 verified_at TIMESTAMPTZ,
 finance_note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(reconciliation_id,transfer_reference)
);
CREATE TABLE IF NOT EXISTS expense_reconciliation_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reconciliation_id BIGINT NOT NULL REFERENCES expense_reconciliations(id) ON DELETE CASCADE,
 actor_id BIGINT REFERENCES users(id),
 event TEXT NOT NULL,note TEXT,created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_exp_reconcile_request ON expense_reconciliations(request_id);
CREATE INDEX IF NOT EXISTS idx_exp_reconcile_owner ON expense_reconciliations(submitted_by,status);
CREATE INDEX IF NOT EXISTS idx_exp_reconcile_review ON expense_reconciliations(status,updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_exp_refunds_review ON expense_reconciliation_refunds(status,created_at DESC);
