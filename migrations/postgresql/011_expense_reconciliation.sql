-- Expense reconciliation linked to a single existing approved purchase request.
-- Additive: no historical request/payment values are rewritten.
CREATE TABLE IF NOT EXISTS expense_reconciliations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reconciliation_no TEXT NOT NULL UNIQUE,
 request_id BIGINT NOT NULL UNIQUE REFERENCES purchase_requests(id) ON DELETE RESTRICT,
 creator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 reviewer_role TEXT NOT NULL,
 reviewer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
 finance_verified_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 original_approved_amount NUMERIC(18,2) NOT NULL CHECK (original_approved_amount>=0),
 original_status TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'Draft',
 actual_total NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (actual_total>=0),
 funding_type TEXT NOT NULL DEFAULT 'Unconfirmed' CHECK (funding_type IN ('Unconfirmed','Budget Only','Employee Advance')),
 released_amount NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (released_amount>=0),
 funding_reference TEXT,
 funding_note TEXT,
 funding_verified_at TIMESTAMPTZ,
 procurement_note TEXT,
 rejection_reason TEXT,
 explanation TEXT,
 submitted_at TIMESTAMPTZ,
 reviewed_at TIMESTAMPTZ,
 completed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS expense_reconciliation_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reconciliation_id BIGINT NOT NULL REFERENCES expense_reconciliations(id) ON DELETE CASCADE,
 request_item_id BIGINT NOT NULL REFERENCES purchase_request_items(id) ON DELETE RESTRICT,
 item_name TEXT NOT NULL,
 item_description TEXT,
 budget_quantity NUMERIC(18,4) NOT NULL CHECK (budget_quantity>=0),
 budget_unit_price NUMERIC(18,2) NOT NULL CHECK (budget_unit_price>=0),
 budget_total NUMERIC(18,2) NOT NULL CHECK (budget_total>=0),
 actual_quantity NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (actual_quantity>=0),
 actual_unit_price NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (actual_unit_price>=0),
 actual_total NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (actual_total>=0),
 note TEXT,
 UNIQUE(reconciliation_id,request_item_id)
);
CREATE TABLE IF NOT EXISTS expense_reconciliation_refunds (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reconciliation_id BIGINT NOT NULL REFERENCES expense_reconciliations(id) ON DELETE RESTRICT,
 amount NUMERIC(18,2) NOT NULL CHECK (amount>0),
 transfer_reference TEXT NOT NULL,
 transfer_date DATE NOT NULL,
 note TEXT,
 status TEXT NOT NULL DEFAULT 'Submitted' CHECK (status IN ('Submitted','Verified','Rejected')),
 submitted_by BIGINT NOT NULL REFERENCES users(id),
 reviewed_by BIGINT REFERENCES users(id),
 review_note TEXT,
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 reviewed_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS expense_reconciliation_evidence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reconciliation_id BIGINT NOT NULL REFERENCES expense_reconciliations(id) ON DELETE CASCADE,
 refund_id BIGINT REFERENCES expense_reconciliation_refunds(id) ON DELETE CASCADE,
 kind TEXT NOT NULL CHECK (kind IN ('Expense Receipt','Refund Proof')),
 file_name TEXT NOT NULL,
 mime_type TEXT NOT NULL,
 byte_length INTEGER NOT NULL CHECK (byte_length>0 AND byte_length<=2500000),
 file_checksum TEXT NOT NULL,
 content BYTEA NOT NULL,
 uploaded_by BIGINT NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS expense_reconciliation_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reconciliation_id BIGINT NOT NULL REFERENCES expense_reconciliations(id) ON DELETE CASCADE,
 actor_id BIGINT NOT NULL REFERENCES users(id),
 action TEXT NOT NULL,
 before_status TEXT,
 after_status TEXT,
 note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_reconciliation_status ON expense_reconciliations(status,reviewer_role,updated_at DESC);
CREATE INDEX IF NOT EXISTS ix_reconciliation_creator ON expense_reconciliations(creator_id,updated_at DESC);
CREATE INDEX IF NOT EXISTS ix_reconciliation_refund ON expense_reconciliation_refunds(reconciliation_id,status);
CREATE INDEX IF NOT EXISTS ix_reconciliation_evidence ON expense_reconciliation_evidence(reconciliation_id,refund_id);
