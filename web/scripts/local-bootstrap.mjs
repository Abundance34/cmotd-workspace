import fs from "node:fs";
import postgres from "postgres";
import { hash } from "@node-rs/argon2";

const databaseUrl = process.env.DATABASE_URL || "postgresql://procureflow:procureflow_local_only@db:5432/procureflow";
const passwordFile = "/run/procureflow-secrets/local_user_password";

if (!fs.existsSync(passwordFile)) {
  throw new Error("Local user password was not generated by the Docker secrets service.");
}

const localPassword = fs.readFileSync(passwordFile, "utf8").trim();
const sql = postgres(databaseUrl, { max: 1, connect_timeout: 10 });

const roles = [
  ["Admin", "ProcureFlow administrator and control-centre operator"],
  ["Facility Manager", "Utility Head / Facility Head requester"],
  ["Procurement Manager", "Procurement review, sourcing and commercial control"],
  ["Approver", "Approver / MD independent approval authority"],
  ["Finance", "Finance payment, receipt and reconciliation operator"],
  ["Logistics Officer", "Logistics delivery, receiving and gateway coordinator"],
  ["Auditor", "Read-only audit, evidence and compliance reviewer"],
];

const permissions = [
  "admin",
  "manage_roles",
  "create_user",
  "manage_users",
  "create_request",
  "view_request",
  "submit_request",
  "source_vendors",
  "manage_vendors",
  "approve_low_value",
  "approve_request",
  "create_purchase_order",
  "approve_purchase_order",
  "approve_payment",
  "approve_gateway_pass",
  "manage_finance",
  "manage_budget",
  "manage_income",
  "manage_logistics",
  "manage_receiving",
  "manage_documents",
  "view_audit",
  "export_reports",
  "manage_notifications",
  "manage_settings",
];

const grants = {
  "Admin": permissions,
  "Facility Manager": ["create_request", "view_request", "submit_request", "manage_documents", "manage_settings"],
  "Procurement Manager": ["create_request", "view_request", "submit_request", "source_vendors", "manage_vendors", "approve_low_value", "create_purchase_order", "manage_documents", "export_reports", "manage_settings"],
  "Approver": ["view_request", "approve_request", "approve_purchase_order", "approve_payment", "approve_gateway_pass", "export_reports", "manage_settings"],
  "Finance": ["view_request", "manage_finance", "manage_budget", "manage_income", "manage_documents", "export_reports", "manage_settings"],
  "Logistics Officer": ["view_request", "manage_logistics", "manage_receiving", "manage_documents", "manage_settings"],
  "Auditor": ["view_request", "view_audit", "export_reports", "manage_settings"],
};

const users = [
  ["admin", "Local Administrator", "Admin"],
  ["facility", "Local Facility Manager", "Facility Manager"],
  ["manager", "Local Procurement Manager", "Procurement Manager"],
  ["approver", "Local Approver / MD", "Approver"],
  ["finance", "Local Finance Officer", "Finance"],
  ["logistics", "Local Logistics Officer", "Logistics Officer"],
  ["auditor", "Local Auditor", "Auditor"],
];

async function waitForSchema() {
  const required = ["users", "roles", "permissions", "role_permissions", "facility_manager_links", "approval_policy_settings"];
  for (let attempt = 1; attempt <= 90; attempt += 1) {
    try {
      const rows = await sql`
        SELECT ${required}::text[] AS required,
               ARRAY[
                 to_regclass('public.users')::text,
                 to_regclass('public.roles')::text,
                 to_regclass('public.permissions')::text,
                 to_regclass('public.role_permissions')::text,
                 to_regclass('public.facility_manager_links')::text,
                 to_regclass('public.approval_policy_settings')::text
               ] AS found
      `;
      if (rows[0]?.found?.every(Boolean)) return;
    } catch {
      // PostgreSQL may still be applying numbered migration files.
    }
    await new Promise((resolve) => setTimeout(resolve, 1000));
  }
  throw new Error("Timed out waiting for the ProcureFlow PostgreSQL schema to initialize.");
}

try {
  await waitForSchema();
  const passwordHash = await hash(localPassword);
  const now = new Date().toISOString();

  await sql.begin(async (tx) => {
    for (const [name, description] of roles) {
      await tx`
        INSERT INTO roles (name, description, created_at)
        VALUES (${name}, ${description}, ${now})
        ON CONFLICT (name) DO UPDATE SET description = EXCLUDED.description
      `;
    }

    for (const name of permissions) {
      await tx`
        INSERT INTO permissions (name, description, created_at)
        VALUES (${name}, ${`Local ProcureFlow permission: ${name}`}, ${now})
        ON CONFLICT (name) DO NOTHING
      `;
    }

    for (const [roleName, rolePermissions] of Object.entries(grants)) {
      for (const permissionName of rolePermissions) {
        await tx`
          INSERT INTO role_permissions (role_name, permission_name, created_at)
          VALUES (${roleName}, ${permissionName}, ${now})
          ON CONFLICT (role_name, permission_name) DO NOTHING
        `;
      }
    }

    for (const [username, fullName, role] of users) {
      await tx`
        INSERT INTO users (
          username, full_name, role, password_hash, must_change_password,
          is_active, account_locked, failed_login_count, created_at, updated_at
        ) VALUES (
          ${username}, ${fullName}, ${role}, ${passwordHash}, FALSE,
          TRUE, FALSE, 0, ${now}, ${now}
        )
        ON CONFLICT (username) DO UPDATE SET
          full_name = EXCLUDED.full_name,
          role = EXCLUDED.role,
          password_hash = EXCLUDED.password_hash,
          must_change_password = FALSE,
          is_active = TRUE,
          account_locked = FALSE,
          failed_login_count = 0,
          updated_at = EXCLUDED.updated_at
      `;
    }

    const linkedUsers = await tx`
      SELECT id, username FROM users WHERE username IN ('facility', 'manager', 'admin')
    `;
    const ids = Object.fromEntries(linkedUsers.map((row) => [row.username, Number(row.id)]));
    if (ids.facility && ids.manager) {
      await tx`
        INSERT INTO facility_manager_links (
          facility_manager_user_id, procurement_manager_user_id, is_active,
          created_by, created_at, updated_at
        ) VALUES (${ids.facility}, ${ids.manager}, 1, ${ids.admin || null}, ${now}, ${now})
        ON CONFLICT (facility_manager_user_id, procurement_manager_user_id)
        DO UPDATE SET is_active = 1, updated_at = EXCLUDED.updated_at
      `;
    }

    await tx`
      INSERT INTO approval_policy_settings (
        policy_key, amount, updated_by, update_reason, created_at, updated_at
      ) VALUES (
        'procurement_manager_approval_limit', 2000000, ${ids.admin || null},
        'Local Docker bootstrap default: Procurement Manager low-value limit', ${now}, ${now}
      )
      ON CONFLICT (policy_key) DO NOTHING
    `;
  });

  console.log("ProcureFlow local PostgreSQL bootstrap complete.");
  console.log("Local users: admin, facility, manager, approver, finance, logistics, auditor");
  console.log("Procurement Manager default low-value approval limit: NGN 2,000,000 (Admin changes are preserved across rebuilds).");
  console.log("All local users use the generated password stored in the Docker secrets volume.");
} finally {
  await sql.end({ timeout: 5 });
}
